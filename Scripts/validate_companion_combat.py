    code=code.replace('(Utilities|IsValidClass (Game|GetObjectClass (Class|BPCompanionCombat|GetCompanion :self D))))','(Class|BPCompanionCombat|Valid :self D :Object (Class|BPCompanionCombat|GetCompanion :self D))')
